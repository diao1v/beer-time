// I2S celebration chime driver for a MAX98357A-class amplifier.
// See bell.h for wiring and peripheral notes.

#include <Arduino.h>
#include <math.h>
#include <string.h>
#include "driver/i2s.h"
#include "bell.h"

namespace {

// I2S_NUM_1 is taken by the HUB75 panel driver, so audio uses I2S_NUM_0.
constexpr i2s_port_t I2S_PORT = I2S_NUM_0;
constexpr int PIN_BCLK = 18;
constexpr int PIN_LRCK = 21;   // word-select / LRCLK
constexpr int PIN_DOUT = 22;   // amp DIN (labeled "SDA" on the module)

constexpr int SAMPLE_RATE = 16000;
float VOLUME = 0.30f;   // 0..1 — final peak level of the mixed bell

// --- IPO-style ringing bell (ported from tools/bell_synth.py) ---
// Inharmonic partials (non-integer ratios) are what make it read as struck
// metal rather than a pure chime. Each: {freq ratio, relative amp, decay/sec}.
constexpr float FUNDAMENTAL_HZ = 740.0f;
struct Partial { float ratio, amp, decay; };
constexpr Partial PARTIALS[] = {
  {0.50f,  0.45f,  2.5f},   // hum — sub-octave undertone
  {1.00f,  1.00f,  4.0f},   // prime — main "dang" pitch
  {1.183f, 0.65f,  5.5f},   // tierce — inharmonic minor 3rd (the bell character)
  {1.506f, 0.45f,  6.5f},   // quint — inharmonic fifth
  {2.00f,  0.55f,  5.5f},   // nominal — octave above prime
  {2.61f,  0.30f,  9.0f},   // inharmonic twelfth-ish
  {3.84f,  0.18f, 13.0f},   // high partial — clang attack
  {5.42f,  0.10f, 20.0f},   // ultra-high shimmer
};
constexpr int NUM_PARTIALS = sizeof(PARTIALS) / sizeof(PARTIALS[0]);

// Overlapping strikes, like a bell tower.
constexpr float STRIKE_INTERVAL_S = 0.30f;   // time between strike onsets
constexpr float STRIKE_DUR_S      = 1.50f;   // per-strike ring length
constexpr float DECAY_MULT        = 0.60f;   // <1 slows decay → longer metallic tail
constexpr int   RING_COUNT        = 10;       // number of strikes
constexpr float ATTACK_S          = 0.003f;  // tiny ramp to avoid an onset click
constexpr float RELEASE_S         = 0.004f;  // fade the tail cutoff to avoid a click

constexpr int STRIKE_SAMPLES  = (int)(STRIKE_DUR_S * SAMPLE_RATE);       // per-strike life
constexpr int STRIKE_STEP     = (int)(STRIKE_INTERVAL_S * SAMPLE_RATE);  // onset spacing
constexpr int ATTACK_SAMPLES  = (int)(ATTACK_S * SAMPLE_RATE);
constexpr int RELEASE_SAMPLES = (int)(RELEASE_S * SAMPLE_RATE);
const int TOTAL_SAMPLES = (RING_COUNT - 1) * STRIKE_STEP + STRIKE_SAMPLES;

// Each partial is generated by a recurrence instead of a per-sample sin/exp:
// a complex phasor z is rotated and shrunk each sample by w = r·e^{jθ}, where
// θ = 2π·f/SR (pitch) and r = e^{-decay/SR} (per-sample decay). Im(z) traces a
// decaying sine. This is cheap enough to run live — no big precomputed buffer.
float wr[NUM_PARTIALS], wi[NUM_PARTIALS];   // per-sample rotation·decay multiplier
float amp0[NUM_PARTIALS];                    // initial phasor magnitude per partial
float mixScale = 0.0f;                       // raw mix → int16 at VOLUME

// One active strike: a bank of partial phasors + its age in samples.
struct Voice {
  bool    active;
  int32_t n;
  float   zr[NUM_PARTIALS], zi[NUM_PARTIALS];
};
Voice   voices[RING_COUNT];
int32_t seqPos     = 0;   // sample index within the whole bell sequence
int     started    = 0;   // strikes started so far

// Cross-core flags (set by trigger() on another core; read by the audio task).
volatile bool restartReq = false;
volatile bool playing    = false;

void startVoice(Voice &v) {
  v.active = true;
  v.n = 0;
  for (int p = 0; p < NUM_PARTIALS; p++) { v.zr[p] = amp0[p]; v.zi[p] = 0.0f; }
}

void resetSeq() {
  seqPos = 0;
  started = 0;
  for (int k = 0; k < RING_COUNT; k++) voices[k].active = false;
}

// Advance the whole mix by one sample; returns the raw (un-scaled) sum.
float stepMixRaw() {
  while (started < RING_COUNT && seqPos >= (int32_t)started * STRIKE_STEP)
    startVoice(voices[started++]);

  float acc = 0.0f;
  for (int k = 0; k < RING_COUNT; k++) {
    Voice &v = voices[k];
    if (!v.active) continue;
    float vs = 0.0f;
    for (int p = 0; p < NUM_PARTIALS; p++) {
      float nzr = v.zr[p] * wr[p] - v.zi[p] * wi[p];
      float nzi = v.zr[p] * wi[p] + v.zi[p] * wr[p];
      v.zr[p] = nzr; v.zi[p] = nzi;
      vs += nzi;                        // Im(z) = amp · r^n · sin(nθ)
    }
    if (v.n < ATTACK_SAMPLES) vs *= (float)v.n / ATTACK_SAMPLES;
    int rel = STRIKE_SAMPLES - v.n;
    if (rel < RELEASE_SAMPLES) vs *= (float)rel / RELEASE_SAMPLES;
    acc += vs;
    if (++v.n >= STRIKE_SAMPLES) v.active = false;
  }
  seqPos++;
  return acc;
}

// Compute the per-partial coefficients, then a fast dry run to find the mix
// peak so we can normalize to VOLUME without clipping. ~50 ms, once at boot.
void calibrate() {
  for (int p = 0; p < NUM_PARTIALS; p++) {
    float theta = 2.0f * PI * FUNDAMENTAL_HZ * PARTIALS[p].ratio / SAMPLE_RATE;
    float r     = expf(-PARTIALS[p].decay * DECAY_MULT / SAMPLE_RATE);
    wr[p]   = r * cosf(theta);
    wi[p]   = r * sinf(theta);
    amp0[p] = PARTIALS[p].amp;
  }
  resetSeq();
  float peak = 1e-6f;
  for (int i = 0; i < TOTAL_SAMPLES; i++) {
    float a = fabsf(stepMixRaw());
    if (a > peak) peak = a;
  }
  mixScale = VOLUME * 32767.0f / peak;
  resetSeq();
}

// Continuously feeds I2S: the bell while playing, silence otherwise. i2s_write
// blocks on the DMA buffers, which paces the loop without a busy-wait.
void audioTask(void *) {
  constexpr int FRAMES = 128;
  int16_t buf[FRAMES * 2];   // interleaved L/R
  for (;;) {
    if (restartReq) { restartReq = false; resetSeq(); playing = true; }

    if (playing) {
      for (int i = 0; i < FRAMES; i++) {
        float raw = (seqPos < TOTAL_SAMPLES) ? stepMixRaw() : 0.0f;
        float out = raw * mixScale;
        if (out > 32767.0f)  out = 32767.0f;
        if (out < -32768.0f) out = -32768.0f;
        int16_t v = (int16_t)out;
        buf[2 * i] = v;
        buf[2 * i + 1] = v;
      }
      if (seqPos >= TOTAL_SAMPLES) playing = false;
    } else {
      memset(buf, 0, sizeof(buf));   // silence: valid clock + zero data = quiet amp
    }

    size_t written = 0;
    i2s_write(I2S_PORT, buf, sizeof(buf), &written, portMAX_DELAY);
  }
}

} // namespace

namespace Bell {

void begin() {
  i2s_config_t cfg = {};
  cfg.mode                 = (i2s_mode_t)(I2S_MODE_MASTER | I2S_MODE_TX);
  cfg.sample_rate          = SAMPLE_RATE;
  cfg.bits_per_sample      = I2S_BITS_PER_SAMPLE_16BIT;
  cfg.channel_format       = I2S_CHANNEL_FMT_RIGHT_LEFT;   // stereo (amp sums L+R)
  cfg.communication_format = I2S_COMM_FORMAT_STAND_I2S;
  cfg.intr_alloc_flags     = ESP_INTR_FLAG_LEVEL1;
  cfg.dma_buf_count        = 6;
  cfg.dma_buf_len          = 256;
  cfg.use_apll             = false;
  cfg.tx_desc_auto_clear   = true;
  cfg.fixed_mclk           = 0;

  i2s_pin_config_t pins = {};
  pins.mck_io_num   = I2S_PIN_NO_CHANGE;
  pins.bck_io_num   = PIN_BCLK;
  pins.ws_io_num    = PIN_LRCK;
  pins.data_out_num = PIN_DOUT;
  pins.data_in_num  = I2S_PIN_NO_CHANGE;

  esp_err_t e = i2s_driver_install(I2S_PORT, &cfg, 0, NULL);
  if (e != ESP_OK) {
    Serial.printf("[bell] i2s install failed: %d\n", (int)e);
    return;
  }
  i2s_set_pin(I2S_PORT, &pins);
  i2s_zero_dma_buffer(I2S_PORT);

  uint32_t t0 = millis();
  calibrate();   // coefficients + mix normalization (no big buffer, ~50 ms)
  Serial.printf("[bell] ready in %lu ms (I2S0, BCLK=18 WS=21 DOUT=22, %.2fs bell)\n",
                (unsigned long)(millis() - t0), (float)TOTAL_SAMPLES / SAMPLE_RATE);

  // Pin the audio task to core 0; the Arduino loop + panel run on core 1.
  xTaskCreatePinnedToCore(audioTask, "bell_audio", 4096, nullptr, 2, nullptr, 0);
}

void trigger() {
  restartReq = true;
}

} // namespace Bell
